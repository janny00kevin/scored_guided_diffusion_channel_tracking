%% SE_vs_SNR_plot.m
% Recreate the Python SE-versus-SNR outputs as editable MATLAB .fig files.
% This script creates:
%   1. SE_vs_SNR_<frequency>GHz_curves.fig
%   2. SE_vs_SNR_table_<frequency>GHz.fig
%
% Both files are saved beside the Python PNG files in SE_vs_SNR_result.

clear;
clc;

%% 1. Path and simulation settings
scriptDir = fileparts(mfilename('fullpath'));
resultDir = fullfile(scriptDir, 'SE_vs_SNR_result');

FREQ_GHZ = 38;


if FREQ_GHZ == 12
    RT_LIST = [64, 60];
elseif FREQ_GHZ == 38
    RT_LIST = [64, 54];

% Match Python's list formatting exactly: [64, 60]
rtTextParts = arrayfun(@(value) sprintf('%g', value), ...
    RT_LIST, 'UniformOutput', false);
rtListText = ['[', strjoin(rtTextParts, ', '), ']'];

matFilename = sprintf( ...
    'SE_vs_SNR_%dGHz_rT%s.mat', FREQ_GHZ, rtListText);
matFilepath = fullfile(resultDir, matFilename);

if ~isfile(matFilepath)
    error(['Could not find the data file at:\n%s\n', ...
           'Please make sure you have run SE_vs_SNR.py first.'], ...
           matFilepath);
end

%% 2. Load data
fprintf('Loading data from %s...\n', matFilename);
data = load(matFilepath);

if ~isfield(data, 'SNR_DB_RANGE') || ~isfield(data, 'result_port')
    error('The MAT file must contain SNR_DB_RANGE and result_port.');
end

SNR_DB_RANGE = data.SNR_DB_RANGE(:);
resultPort = data.result_port(:);

if numel(resultPort) ~= numel(SNR_DB_RANGE)
    error('SNR_DB_RANGE and result_port must have the same length.');
end

resultsModal = cell(1, numel(RT_LIST));

for rtIndex = 1:numel(RT_LIST)
    keyName = sprintf('rate_modal_%g', RT_LIST(rtIndex));

    if ~isfield(data, keyName)
        error('Required variable "%s" is missing from %s.', ...
            keyName, matFilename);
    end

    resultsModal{rtIndex} = data.(keyName);
    resultsModal{rtIndex} = resultsModal{rtIndex}(:);

    if numel(resultsModal{rtIndex}) ~= numel(SNR_DB_RANGE)
        error('%s and SNR_DB_RANGE must have the same length.', keyName);
    end
end

%% 3. Rate-comparison curves
fprintf('Generating Rate Comparison Curves...\n');

% Matplotlib's default figure size is 6.4 by 4.8 inches.
curveFig = figure( ...
    'Color', 'white', ...
    'Units', 'inches', ...
    'Position', [1, 1, 6.4, 4.8], ...
    'PaperPositionMode', 'auto');

curveAx = axes(curveFig);
hold(curveAx, 'on');

curveHandles = gobjects(1, numel(RT_LIST) + 1);
legendLabels = cell(1, numel(RT_LIST) + 1);

curveHandles(1) = plot(curveAx, SNR_DB_RANGE, resultPort, ...
    'Color', [0, 0, 0], ...
    'LineStyle', '-', ...
    'LineWidth', 2.5, ...
    'Marker', 'o', ...
    'MarkerSize', 6, ...
    'MarkerFaceColor', [0, 0, 0], ...
    'MarkerEdgeColor', [0, 0, 0]);
legendLabels{1} = 'Port-domain Full-Digital Bound';

markers = {'s', '^', 'v', 'd', 'p', '*'};

% Matplotlib tab10 colors, matching the first curves in its default cycle.
matplotlibColors = [ ...
     31, 119, 180; ...
    255, 127,  14; ...
     44, 160,  44; ...
    214,  39,  40; ...
    148, 103, 189; ...
    140,  86,  75; ...
    227, 119, 194; ...
    127, 127, 127; ...
    188, 189,  34; ...
     23, 190, 207] / 255;

for rtIndex = 1:numel(RT_LIST)
    marker = markers{mod(rtIndex - 1, numel(markers)) + 1};
    color = matplotlibColors( ...
        mod(rtIndex - 1, size(matplotlibColors, 1)) + 1, :);

    curveHandles(rtIndex + 1) = plot( ...
        curveAx, SNR_DB_RANGE, resultsModal{rtIndex}, ...
        'Color', color, ...
        'LineStyle', '--', ...
        'LineWidth', 1.5, ...
        'Marker', marker, ...
        'MarkerSize', 6, ...
        'MarkerFaceColor', color, ...
        'MarkerEdgeColor', color);

    legendLabels{rtIndex + 1} = sprintf( ...
        'Modal-domain (r_T=%g)', RT_LIST(rtIndex));
end

xlabel(curveAx, 'SNR (dB)', ...
    'FontName', 'Helvetica', ...
    'FontSize', 12, ...
    'Interpreter', 'none');

ylabel(curveAx, 'Average Rate (bps/Hz)', ...
    'FontName', 'Helvetica', ...
    'FontSize', 12, ...
    'Interpreter', 'none');

title(curveAx, sprintf( ...
    'Average Sum Rate Comparison (%dGHz Imperfect CSI)', FREQ_GHZ), ...
    'FontName', 'Helvetica', ...
    'FontSize', 14, ...
    'FontWeight', 'normal', ...
    'Interpreter', 'none');

set(curveAx, ...
    'FontName', 'Helvetica', ...
    'FontSize', 10, ...
    'Box', 'on', ...
    'GridLineStyle', ':', ...
    'GridAlpha', 0.7, ...
    'Layer', 'bottom');
grid(curveAx, 'on');

legend(curveAx, curveHandles, legendLabels, ...
    'Location', 'northwest', ...
    'FontName', 'Helvetica', ...
    'FontSize', 10, ...
    'Interpreter', 'tex', ...
    'Box', 'on');

% Matplotlib normally adds approximately 5% horizontal data margin.
snrMin = min(SNR_DB_RANGE);
snrMax = max(SNR_DB_RANGE);
snrSpan = snrMax - snrMin;
if snrSpan > 0
    xlim(curveAx, [snrMin - 0.05*snrSpan, snrMax + 0.05*snrSpan]);
end

hold(curveAx, 'off');
drawnow;

% Approximate bbox_inches='tight' while keeping the MATLAB figure editable.
set(curveAx, 'LooseInset', ...
    max(get(curveAx, 'TightInset'), [0.02, 0.02, 0.02, 0.02]));

curveBaseName = sprintf('SE_vs_SNR_%dGHz_curves', FREQ_GHZ);
curveFigPath = fullfile(resultDir, [curveBaseName, '.fig']);
savefig(curveFig, curveFigPath);
close(curveFig);

fprintf('[Success] Saved editable curves:\n%s\n', curveFigPath);

%% 4. Modal-efficiency percentage table
fprintf('Generating Modal Efficiency Table...\n');

numberOfRows = numel(SNR_DB_RANGE);
numberOfModes = numel(RT_LIST);
tableData = cell(numberOfRows, numberOfModes);

for snrIndex = 1:numberOfRows
    portValue = resultPort(snrIndex);

    for rtIndex = 1:numberOfModes
        modalValue = resultsModal{rtIndex}(snrIndex);
        percentage = (modalValue / portValue)*100;
        tableData{snrIndex, rtIndex} = sprintf('%.2f%%', percentage);
    end
end

columnLabels = arrayfun( ...
    @(rt) sprintf('Modal (rT=%g)', rt), ...
    RT_LIST, 'UniformOutput', false);
rowLabels = arrayfun( ...
    @(snr) sprintf('%g dB', snr), ...
    SNR_DB_RANGE, 'UniformOutput', false);

tableFig = figure( ...
    'Color', 'white', ...
    'Units', 'inches', ...
    'Position', [1, 1, 10, 6], ...
    'PaperPositionMode', 'auto');

annotation(tableFig, 'textbox', [0.04, 0.88, 0.92, 0.08], ...
    'String', sprintf([ ...
        'Modal Efficiency Relative to Port-domain Bound (%%) - ', ...
        '%dGHz'], FREQ_GHZ), ...
    'HorizontalAlignment', 'center', ...
    'VerticalAlignment', 'middle', ...
    'FontName', 'Helvetica', ...
    'FontSize', 13, ...
    'FontWeight', 'bold', ...
    'Interpreter', 'none', ...
    'EdgeColor', 'none');

% Matplotlib scales its default table by 1.2 horizontally and 1.6 vertically.
tableHeight = min(0.68, 0.070*(numberOfRows + 1));
tableBottom = 0.47 - tableHeight/2;
tableBottom = max(0.08, tableBottom);

tableAx = axes(tableFig, ...
    'Units', 'normalized', ...
    'Position', [0.08, tableBottom, 0.84, tableHeight], ...
    'Visible', 'off', ...
    'XLim', [0, 1], ...
    'YLim', [0, numberOfRows + 1]);
hold(tableAx, 'on');

rowLabelWidth = 0.20;
dataColumnWidth = (1 - rowLabelWidth) / numberOfModes;
edgeColor = [0.35, 0.35, 0.35];
rowLabelColor = [241, 241, 241] / 255;
columnHeaderColor = [207, 226, 243] / 255;

% Blank upper-left corner cell.
rectangle(tableAx, ...
    'Position', [0, numberOfRows, rowLabelWidth, 1], ...
    'FaceColor', 'white', ...
    'EdgeColor', 'white', ...
    'LineWidth', 0.5);

% Blue column-header cells.
for rtIndex = 1:numberOfModes
    xPosition = rowLabelWidth + (rtIndex - 1)*dataColumnWidth;

    rectangle(tableAx, ...
        'Position', [xPosition, numberOfRows, dataColumnWidth, 1], ...
        'FaceColor', columnHeaderColor, ...
        'EdgeColor', edgeColor, ...
        'LineWidth', 0.5);

    text(tableAx, xPosition + dataColumnWidth/2, numberOfRows + 0.5, ...
        columnLabels{rtIndex}, ...
        'HorizontalAlignment', 'center', ...
        'VerticalAlignment', 'middle', ...
        'FontName', 'Helvetica', ...
        'FontSize', 11, ...
        'Interpreter', 'none');
end

% Gray SNR-label cells and white percentage cells.
for snrIndex = 1:numberOfRows
    yPosition = numberOfRows - snrIndex;

    rectangle(tableAx, ...
        'Position', [0, yPosition, rowLabelWidth, 1], ...
        'FaceColor', rowLabelColor, ...
        'EdgeColor', edgeColor, ...
        'LineWidth', 0.5);

    text(tableAx, 0.10*rowLabelWidth, yPosition + 0.5, ...
        rowLabels{snrIndex}, ...
        'HorizontalAlignment', 'left', ...
        'VerticalAlignment', 'middle', ...
        'FontName', 'Helvetica', ...
        'FontSize', 11, ...
        'Interpreter', 'none');

    for rtIndex = 1:numberOfModes
        xPosition = rowLabelWidth + (rtIndex - 1)*dataColumnWidth;

        rectangle(tableAx, ...
            'Position', [xPosition, yPosition, dataColumnWidth, 1], ...
            'FaceColor', 'white', ...
            'EdgeColor', edgeColor, ...
            'LineWidth', 0.5);

        text(tableAx, xPosition + dataColumnWidth/2, yPosition + 0.5, ...
            tableData{snrIndex, rtIndex}, ...
            'HorizontalAlignment', 'center', ...
            'VerticalAlignment', 'middle', ...
            'FontName', 'Helvetica', ...
            'FontSize', 11, ...
            'Interpreter', 'none');
    end
end

axis(tableAx, 'off');
hold(tableAx, 'off');
drawnow;

tableBaseName = sprintf('SE_vs_SNR_table_%dGHz', FREQ_GHZ);
tableFigPath = fullfile(resultDir, [tableBaseName, '.fig']);
% savefig(tableFig, tableFigPath);
close(tableFig);

fprintf('[Success] Saved editable table:\n%s\n', tableFigPath);
fprintf('\nSuccess! Both editable figures have been saved to:\n%s\n', ...
    resultDir);
